#!/usr/bin/env python3
"""Architecture ratchet for mamadera — enforces the layer rules in AGENTS.md.

Why a ratchet and not a clean-slate rule: the codebase carries a handful of
grandfathered violations (documented in architecture_baseline.json). A rule that
fails on day one gets switched off; a rule that only fails on NEW violations
survives, and the baseline shrinks over time.

Checks (all read-only, no toolchain needed, ~0.5 s):
  1. domain/         must not import a framework  (flutter, flutter_riverpod, riverpod, drift, go_router)
  2. presentation/   must not import lib/data/**  (repository providers only — AGENTS.md)
  3. any relative import that escapes lib/        (resolves today only by package-root clamping)
  4. core/           must not import features/*/presentation/**  (inverted dependency)
  5. no non-generated lib/ file above MAX_FILE_LINES
  6. one_member_abstracts are declared in domain/, not in presentation/

Usage:
    python3 scripts/check_architecture.py                 # check against the baseline
    python3 scripts/check_architecture.py --update        # re-lock the baseline (lower = better)
    python3 scripts/check_architecture.py --report        # full inventory, never fails

Exit code: 0 at or below baseline, 1 on any regression.
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASELINE_PATH = os.path.join(ROOT, "scripts", "architecture_baseline.json")
MAX_FILE_LINES = 800

FRAMEWORK_PACKAGES = ("flutter", "flutter_riverpod", "riverpod", "drift", "go_router")
GENERATED_SUFFIXES = (".g.dart", ".freezed.dart")
# Generated by `flutter gen-l10n` — never hand-written, never length-limited.
GENERATED_PREFIXES = ("lib/l10n/",)
# A router is ALLOWED to import screens: that is the whole job of lib/core/router.dart.
# Exempting it keeps rule 4 pointed at what is actually an inverted dependency
# (core/providers/* reaching into features/baby/presentation).
ROUTER_EXEMPT = ("lib/core/router.dart",)

IMPORT_RE = re.compile(r"""^\s*import\s+['"]([^'"]+)['"]""", re.M)
EXPORT_RE = re.compile(r"^\s*export\s+['\"]([^'\"]+)['\"]", re.M)


def lib_files():
    """Every hand-written Dart file under lib/, repo-relative."""
    base = os.path.join(ROOT, "lib")
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = [d for d in dirnames if d not in (".dart_tool",)]
        for name in filenames:
            if not name.endswith(".dart") or name.endswith(GENERATED_SUFFIXES):
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), ROOT)
            if rel.startswith(GENERATED_PREFIXES):
                continue
            yield rel


def layer_of(rel: str) -> tuple[str, str]:
    """('features/home', 'presentation') for lib/features/home/presentation/..."""
    parts = rel.split("/")
    if parts[0] != "lib":
        return ("outside-lib", "")
    if len(parts) >= 4 and parts[1] == "features":
        return (f"features/{parts[2]}", parts[3])
    if len(parts) >= 2:
        return (parts[1], parts[1])
    return ("root", "root")


def resolve(importer: str, target: str) -> str | None:
    """Resolve a relative import the way the compiler does, WITHOUT clamping."""
    if target.startswith("package:mamadera/"):
        return os.path.normpath("lib/" + target[len("package:mamadera/"):])
    if target.startswith("package:") or target.startswith("dart:"):
        return None
    return os.path.normpath(os.path.join(os.path.dirname(importer), target))


def collect():
    violations: dict[str, list[str]] = collections.defaultdict(list)

    for rel in lib_files():
        text = open(os.path.join(ROOT, rel), encoding="utf-8", errors="replace").read()
        feature, layer = layer_of(rel)

        for raw in IMPORT_RE.findall(text):
            pkg = raw.split("/")[0]
            resolved = resolve(rel, raw)

            # 3 — escapes lib/ (works today only because the front end clamps at the package root)
            if raw.startswith(".") and resolved is not None and not resolved.startswith("lib/"):
                violations["escaped_imports"].append(f"{rel}: {raw}")

            # 1 — domain must be pure Dart
            if "/domain/" in f"/{rel}" and pkg in FRAMEWORK_PACKAGES:
                violations["domain_framework_imports"].append(f"{rel}: {raw}")

            if resolved is None:
                continue

            tfeature, tlayer = layer_of(resolved)

            # 2 — presentation must not reach into the data layer
            if layer == "presentation" and resolved.startswith("lib/data/"):
                violations["presentation_to_data"].append(f"{rel}: {raw}")

            # 4 — core must not depend on a feature's presentation layer
            if (feature == "core" and tfeature.startswith("features/") and tlayer == "presentation"
                    and rel not in ROUTER_EXEMPT):
                violations["core_to_feature_presentation"].append(f"{rel}: {raw}")

        # 5 — file length
        lines = text.count("\n") + 1
        if lines > MAX_FILE_LINES:
            violations["oversized_files"].append(f"{rel}: {lines} lines > {MAX_FILE_LINES}")

    return violations


def main() -> int:
    ap = argparse.ArgumentParser(description="Architecture ratchet (see module docstring)")
    ap.add_argument("--update", action="store_true", help="lock current counts as the new baseline")
    ap.add_argument("--report", action="store_true", help="print every violation, always exit 0")
    args = ap.parse_args()

    os.chdir(ROOT)
    violations = collect()
    keys = ("domain_framework_imports", "presentation_to_data",
            "escaped_imports", "core_to_feature_presentation", "oversized_files")
    counts = {k: len(violations.get(k, [])) for k in keys}

    if args.report:
        for key, items in violations.items():
            print(f"\n{key} ({len(items)})")
            for item in sorted(items):
                print(f"  {item}")
        return 0

    if args.update or not os.path.exists(BASELINE_PATH):
        with open(BASELINE_PATH, "w", encoding="utf-8") as fh:
            json.dump({"_comment": "Ratchet: counts may only go down. Regenerate with --update.",
                      "max_file_lines": MAX_FILE_LINES, "counts": counts,
                      "detail": {k: sorted(v) for k, v in violations.items()}},
                      fh, indent=2, sort_keys=True)
        print(f"baseline written: {BASELINE_PATH}\n{json.dumps(counts, indent=2)}")
        return 0

    baseline = json.load(open(BASELINE_PATH, encoding="utf-8"))["counts"]
    regressions = {k: (counts[k], baseline.get(k, 0)) for k in counts if counts[k] > baseline.get(k, 0)}
    improvements = {k: (counts[k], baseline.get(k, 0)) for k in counts if counts[k] < baseline.get(k, 0)}

    print("architecture ratchet")
    for key, now in counts.items():
        floor = baseline.get(key, 0)
        mark = "❌" if key in regressions else ("✨" if key in improvements else "✅")
        print(f"  {mark} {key:32s} {now:3d}  (baseline {floor})")

    if improvements:
        print("\nSome counts dropped — tighten the baseline:")
        print("  python3 scripts/check_architecture.py --update")

    for key, (now, floor) in regressions.items():
        print(f"\n❌ {key}: {now} > baseline {floor}. New violations:")
        known = set(json.load(open(BASELINE_PATH, encoding="utf-8")).get("detail", {}).get(key, []))
        for item in sorted(set(violations[key]) - known):
            print(f"     {item}")
        if set(violations[key]) == known:
            print("     (same items as baseline — a counted rule exceeded its cap)")
    return 1 if regressions else 0


if __name__ == "__main__":
    sys.exit(main())
