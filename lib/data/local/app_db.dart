  /// SQL indexes are automatically created during the database initialization process.
  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (Migrator m) async {
          await m.createAll();
          // Create indexes after the tables.
          await m.database.customStatement(
              'CREATE INDEX IF NOT EXISTS idx_tracking_events_type ON tracking_events(type)');
          await m.database.customStatement(
              'CREATE INDEX IF NOT EXISTS idx_tracking_events_timestamp_type ON tracking_events(timestamp DESC, type)');
          // Index v11: Without them, new installations would only have...
          // two historical indexes, while the migrated databases have four—one.
          // A barely perceptible gap in the test, but visible when scrolling on a phone.
          await m.database.customStatement(
              'CREATE INDEX IF NOT EXISTS idx_measurements_baby_kind_recorded ON measurements(baby_id, kind, recorded_at DESC)');
          await m.database.customStatement(
              'CREATE INDEX IF NOT EXISTS idx_reminder_completions_baby_item ON reminder_completions(baby_id, item_id, completed_at DESC)');
        },
        onUpgrade: (Migrator m, int from, int to) async {
          // v2 → v3 : ajout de la table reminder_dismissals
          if (from < 3) {
            await m.createTable(reminderDismissals);
            // Recreate the indexes if they are missing (safely, using the "IF NOT EXISTS" clause).
            await m.database.customStatement(
                'CREATE INDEX IF NOT EXISTS idx_tracking_events_type ON tracking_events(type)');
            await m.database.customStatement(
                'CREATE INDEX IF NOT EXISTS idx_tracking_events_timestamp_type ON tracking_events(timestamp DESC, type)');
          }
          // v3 → v4 : ajout de baby_profiles + baby_id nullable sur tracking_events (backward compatible)
          if (from < 4) {
            await m.createTable(babyProfiles);
            await m.database.customStatement(
                'ALTER TABLE tracking_events ADD COLUMN baby_id TEXT');
          }
          // v4 → v5: Added a subtype column and migrated legacy data (health subtypes within wasteType).
          if (from < 5) {
            await m.database.customStatement(
                'ALTER TABLE tracking_events ADD COLUMN subtype TEXT');
            // Migrate health events: copy the `wasteType` field to `subtype` and then delete the `wasteType` field.
            await m.database.customStatement(
                "UPDATE tracking_events SET subtype = waste_type, waste_type = NULL WHERE type = 'sante'");
            // Migrate the feeding events: set the default subtype to 'breast' (the 'bottle' subtype was never being saved).
            await m.database.customStatement(
                "UPDATE tracking_events SET subtype = 'sein' WHERE type = 'miam' AND subtype IS NULL");
          }
          // v5 → v6 : ajout de la colonne quantity (volume ml feeding / minutes sleep)
          if (from < 6) {
            await m.database.customStatement(
                'ALTER TABLE tracking_events ADD COLUMN quantity REAL');
          }
          // v6 → v7 : migration des valeurs de subtype feeding (sein/bib → natural/artificial)
          if (from < 7) {
            await m.database.customStatement(
                "UPDATE tracking_events SET subtype = 'natural' WHERE type = 'miam' AND (subtype IS NULL OR subtype IN ('sein', 'naturel'))");
            await m.database.customStatement(
                "UPDATE tracking_events SET subtype = 'artificial' WHERE type = 'miam' AND subtype IN ('bib', 'artificiel')");
          }
          // v7 → v8: Create the `reminder_settings` if it doesn't already exist.
          // The table was declared in the @DriftDatabase but was never actually created.
          // `onUpgrade`: Any database created before version 7 (versions 3 through 6) would be upgraded to version 8.
          // without the table, and any reading/writing of reminder settings.
          // It failed with the error "no such table: reminder_settings".
          // IF NOT EXISTS: For new installations (onCreate → createAll).
          // already possess.
          if (from < 8) {
            await m.database.customStatement(
              'CREATE TABLE IF NOT EXISTS reminder_settings ('
              'item_id TEXT NOT NULL PRIMARY KEY,'
              'enabled BOOLEAN NOT NULL'
              ')',
            );
          }
          // v8 → v9: Added the "texture" column (consistency of stools).
          // Set to NULL for all layers that have already been saved: this ensures that...
          // It's impossible to determine the texture of a banknote that has already been marked.
          if (from < 9) {
            await m.database.customStatement(
                'ALTER TABLE tracking_events ADD COLUMN texture TEXT');
          }
          // v9 → v10: Personalized reminders table. The `m.createTable` function is being reintroduced.
          // The DDL for the "Drift" table (auto_increment); new installations for it.
          // already receive data in `onCreate` → `createAll`.
          if (from < 10) {
            await m.createTable(customReminders);
          }

          // v10 → v11 : trois mouvements, un seul passage.
          // (a) `reminder_settings` and `reminder_dismissals` are reset by the baby:
          // A reminder that is disabled for one user is no longer disabled for the other (item M).
          //  (b) `custom_reminders` gagne `baby_id` + `completion_source` et surtout
          // `subtype_value` is nullable, which `ALTER TABLE` cannot handle: the...
          //      table est reconstruite.
          //  (c) deux tables neuves : `measurements` et `reminder_completions`.
          // Composite primary keys declare `baby_id NOT NULL`: SQLite allows this.
          // NULL values are allowed in a composite key, and duplicates are permitted (verified in SQLite 3.51).
          // This would result in two "shared" lines for the same reminder. The sentinel.
          // `''` means "all babies."
          // The IDs for `custom_reminders` are explicitly copied: the key.
          // d'extinction `custom_<id>` de `reminder_settings` s'y rapporte, changer un id
          // It would disable a random reminder.
          if (from < 11) {
            // (a) settings
            await m.database.customStatement('''
              CREATE TABLE reminder_settings_new (
                baby_id TEXT    NOT NULL DEFAULT '',
                item_id TEXT    NOT NULL,
                enabled BOOLEAN NOT NULL,
                PRIMARY KEY (baby_id, item_id)
              )''');
            await m.database.customStatement(
                'INSERT INTO reminder_settings_new (baby_id, item_id, enabled) '
                "SELECT '', item_id, enabled FROM reminder_settings");
            await m.database.customStatement('DROP TABLE reminder_settings');
            await m.database.customStatement(
                'ALTER TABLE reminder_settings_new RENAME TO reminder_settings');

            // (a) dismissals
            await m.database.customStatement('''
              CREATE TABLE reminder_dismissals_new (
                baby_id      TEXT    NOT NULL DEFAULT '',
                item_id      TEXT    NOT NULL,
                dismissed_at TIMESTAMP NOT NULL,
                PRIMARY KEY (baby_id, item_id)
              )''');
            await m.database.customStatement(
                'INSERT INTO reminder_dismissals_new (baby_id, item_id, dismissed_at) '
                "SELECT '', item_id, dismissed_at FROM reminder_dismissals");
            await m.database.customStatement('DROP TABLE reminder_dismissals');
            await m.database.customStatement(
                'ALTER TABLE reminder_dismissals_new RENAME TO reminder_dismissals');

            // (b) custom reminders — rebuilt for the nullable subtype_value
            await m.database.customStatement('''
              CREATE TABLE custom_reminders_new (
                id               INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
                baby_id          TEXT    NOT NULL DEFAULT '',
                label            TEXT    NOT NULL,
                subtype_value    TEXT,
                frequency        TEXT    NOT NULL,
                interval_days    INTEGER,
                completion_source TEXT   NOT NULL DEFAULT 'from_events'
              )''');
            await m.database.customStatement(
                'INSERT INTO custom_reminders_new (id, baby_id, label, subtype_value, frequency, interval_days) '
                "SELECT id, '', label, subtype_value, frequency, interval_days FROM custom_reminders");
            await m.database.customStatement('DROP TABLE custom_reminders');
            await m.database.customStatement(
                'ALTER TABLE custom_reminders_new RENAME TO custom_reminders');
            // Safety net: An AUTOINCREMENT field that has been renamed can restart from 1 and potentially cause conflicts.
            // With a copied ID. The migration test catches it; the line prevents it.
            await m.database.customStatement(
                'UPDATE sqlite_sequence SET seq = (SELECT COALESCE(MAX(id), 0) FROM custom_reminders) '
                "WHERE name = 'custom_reminders'");

            // (c) new tables (drift emits the DDL from the classes above)
            await m.createTable(measurements);
            await m.createTable(reminderCompletions);

            await m.database.customStatement(
                'CREATE INDEX IF NOT EXISTS idx_measurements_baby_kind_recorded '
                'ON measurements(baby_id, kind, recorded_at DESC)');
            await m.database.customStatement(
                'CREATE INDEX IF NOT EXISTS idx_reminder_completions_baby_item '
                'ON reminder_completions(baby_id, item_id, completed_at DESC)');
          }

          // v11 → v12:  Added a `unit` designation to each quantity listed (BACKLOG B1).
          //
          // The meaning of `quantity` was **inferred** from the type and subtype; the...
          // the day when `natural` legitimately refers to milliliters (expressed breast milk) or...
          // minutes (timed feedings), inference is no longer sufficient: a...
          // line, two units, with nothing to distinguish them. The unit becomes a...
          // Data from the line.
          //
          // The "backfill" refers to **the unit that the parent saw on the screen**, and never anything else.
          // A guessed intention: a parent who noticed a child holding their breasts read.
          // "20 ml," so the line represents 20 ml. Convert a line.
          // `natural` could invent a measurement in minutes that has never existed before.
          // calculation. There's no arithmetic involved in this section – that's the rule, not an option.
          // oubli.
          //
          // `ALTER TABLE … ADD COLUMN … NOT NULL DEFAULT` is additive and legal
          // on SQLite, even on a populated table. However, a migration is still required, which...
          // downgrade: unable to undo; hence, the use of an emulator on a...
          // device that already contains data from version 11 (AGENTS.md).
          if (from < 12) {
            await m.database.customStatement(
                "ALTER TABLE tracking_events ADD COLUMN unit TEXT NOT NULL DEFAULT 'ml'");
            // The backfill covers every combination where `quantity` is
            // non-null: `dodo` → minutes, `miam` + `solid` → grams, and the
            // remaining rows keep the ALTER's default (`ml`). `sante` and
            // `caca` rows have NULL quantity, so two UPDATEs suffice.
            await m.database.customStatement(
                "UPDATE tracking_events SET unit = 'min' WHERE type = 'dodo'");
            await m.database
                .customStatement("UPDATE tracking_events SET unit = 'g' "
                    "WHERE type = 'miam' AND subtype = 'solid'");

            // Reassign the `''` ("installation without profile") sentinel rows
            // to the single baby where ownership is unambiguous (fix for the
            // v1.2.0 cross-baby leak). On a one-baby install, the pre-isolation
            // state was unambiguously that baby's — keeping it in the
            // profileless scope would save nothing and reassigning it to
            // someone else would destroy it. With zero or multiple babies the
            // ownership cannot be told: the rows stay under `''`, profileless
            // and invisible (decision of 2026-10-04).
            final babies = await m.database
                .customSelect('SELECT COUNT(*) AS n FROM baby_profiles')
                .getSingle();
            final babyCount = babies.read<int>('n');
            if (babyCount == 1) {
              final baby = await m.database
                  .customSelect('SELECT id FROM baby_profiles')
                  .getSingle();
              final babyId = baby.read<String>('id');
              for (final table in [
                'reminder_settings',
                'reminder_dismissals',
                'reminder_completions',
                'custom_reminders',
              ]) {
                await m.database.customStatement(
                  'UPDATE $table SET baby_id = ? WHERE baby_id = ?',
                  [babyId, db_const.sharedBabyId],
                );
              }
            }
          }

          // v12 → v13: `app_settings` table (roadmap item 12) — app-level
          // notification preferences (opt-in flag + preferred time of day).
          // Purely additive: one CREATE TABLE, no rekey, no data movement,
          // no sentinel (the table has no baby dimension).
          if (from < 13) {
            await m.createTable(appSettings);
          }
        },
      );

  Future<List<TrackingEvent>> getEvents() => select(trackingEvents).get();

  Future<int> insertEvent(TrackingEventsCompanion event) =>
      into(trackingEvents).insert(event);

  /// Only return events related to feeding (natural or artificial).
  Future<List<TrackingEvent>> getFeedingEvents() {
    return (select(trackingEvents)
          ..where((t) => t.type.equals(db_const.typeMiam))
          ..orderBy([(t) => OrderingTerm.desc(t.timestamp)]))
        .get();
  }

  Future<List<TrackingEvent>> getAllEventsOrdered() {
    return (select(trackingEvents)
          ..orderBy([(t) => OrderingTerm.desc(t.timestamp)]))
        .get();
  }

  Future<List<TrackingEvent>> getEventsByType(String type) {
    return (select(trackingEvents)
          ..where((t) => t.type.equals(type))
          ..orderBy([(t) => OrderingTerm.desc(t.timestamp)]))
        .get();
  }

  /// Updates an existing event by its ID.
  Future<int> updateEvent(int id, TrackingEventsCompanion companion) {
    return (update(trackingEvents)..where((t) => t.id.equals(id)))
        .write(companion);
  }

  /// Deletes an event by its ID. Returns true if a row was deleted.
  Future<bool> deleteEvent(int id) async {
    final deleted =
        await (delete(trackingEvents)..where((t) => t.id.equals(id))).go();
    return deleted > 0;
  }

  /// Returns all events without any specific sorting.
  Future<List<TrackingEvent>> getAllTrackingEvents() =>
      select(trackingEvents).get();

  /// Updates only the "notes" field of an event, using its ID.
  Future<int> updateNotesForEvent(int id, String? newNotes) {
    return (update(trackingEvents)..where((t) => t.id.equals(id)))
        .write(TrackingEventsCompanion(notes: Value(newNotes)));
  }

  /// ── Baby Profiles Queries ────────────────────────────────────────

  Future<List<BabyProfile>> getAllBabyProfiles() {
    return (select(babyProfiles)..orderBy([(t) => OrderingTerm.asc(t.name)]))
        .get();
  }

  /// Returns the active profile (the row where `is_active` is true), or null.
  ///
  /// Rows are ordered by `birth_date` then `id`, so if two rows ever both
  /// claim active (a bug fixed by the `setActiveProfile` transaction), the
  /// same row is returned every time instead of whichever SQLite happens to
  /// yield first.
  Future<BabyProfile?> getActiveBabyProfile() async {
    final profiles = await (select(babyProfiles)
          ..where((t) => t.isActive.equals(true))
          ..orderBy([
            (t) => OrderingTerm.asc(t.birthDate),
            (t) => OrderingTerm.asc(t.id)
          ]))
        .get();
    return profiles.isEmpty ? null : profiles.first;
  }

