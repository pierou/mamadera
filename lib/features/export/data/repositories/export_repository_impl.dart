import 'dart:convert';

import 'package:logger/logger.dart';

import '../../../../core/config/app_config.dart';
import '../../../../core/services/app_logger.dart';
import '../../../../core/services/encryption_service.dart';
import '../../../../data/local/app_db.dart' as db_app;
import '../../../../data/local/tracking_event_mapper.dart';
import '../../../../shared/domain/entities/tracking_event.dart';
import '../../domain/repositories/export_repository.dart';

/// Concrete implementation of [ExportRepository].
///
/// Reads the entire database (all seven tables, unfiltered), decrypts event
/// notes through the shared tracking event mapper — the single place in the
/// codebase where decryption happens — and serializes everything into the
/// export document. Only counts and timings are logged; no exported content,
/// no name, no note ever reaches the log.
///
/// Reminder labels are exported as stored, like baby names: they are text the
/// parent typed to name a care, not a medical value. The medical fields this
/// app keeps encrypted — notes, weight, allergies — still leave only after
/// decryption through the mapper.
///
/// M4 (format 2): `measurements.value` is decrypted with the same pattern as
/// the event notes and leaves in the clear, on purpose — the backup is the
/// owner's copy of the data, and an unreadable number is no backup. The
/// importer re-encrypts it (fresh IV) before it reaches a database.
class ExportRepositoryImpl implements ExportRepository {
  const ExportRepositoryImpl({
    required this.database,
    required this.encryption,
  });

  final db_app.AppDatabase database;
  final EncryptionService encryption;

  static final Logger _logger = appLogger();

  /// Format of the document generated by this version of the app.
  ///
  /// 2 (M4) : ajout des sections `measurements` et `reminderCompletions`,
  /// `babyId` in the settings/rejection of reminders, `babyId` + ...
  /// `completionSource` for personalized reminders (and `subtypeValue`).
  /// nullable in the latter case).
  /// 3 (v12): `unit` for each event – the exported number represents.
  /// From now on, it should explicitly state its main point, rather than leaving the reader to infer it.
  static const int _exportFormatVersion = 3;

  @override
  Future<String> buildExportJson() async {
    final stopwatch = Stopwatch()..start();

    // UNFILTERED reads: every row of every table, including events whose
    // babyId is null. A backup that quietly omits rows is worse than none.
    final profiles = await database.getAllBabyProfiles();
    final events = await database.getAllTrackingEvents();
    final customReminders = await database.getAllCustomReminders();
    final settings = await database.getAllReminderSettings();
    final dismissals = await database.getAllReminderDismissals();
    final measurements = await database.getAllMeasurements();
    final completions = await database.getAllReminderCompletions();
    stopwatch.stop();

    // Counts and timings only — never any exported content.
    _logger.d(
      'buildExportJson: profiles=${profiles.length} events=${events.length} '
      'customReminders=${customReminders.length} '
      'settings=${settings.length} dismissals=${dismissals.length} '
      'measurements=${measurements.length} completions=${completions.length} '
      'in ${stopwatch.elapsedMilliseconds} ms',
    );

    final document = <String, Object?>{
      'exportFormatVersion': _exportFormatVersion,
      'generator': 'mamadera',
      'appVersion': AppConfig.version,
      'databaseSchemaVersion': database.schemaVersion,
      'exportedAt': DateTime.now().toUtc().toIso8601String(),
      'counts': <String, Object?>{
        'babyProfiles': profiles.length,
        'trackingEvents': events.length,
        'customReminders': customReminders.length,
        'reminderSettings': settings.length,
        'reminderDismissals': dismissals.length,
        'measurements': measurements.length,
        'reminderCompletions': completions.length,
      },
      'babyProfiles': _mapProfiles(profiles),
      'trackingEvents': _mapEvents(events),
      'customReminders': [
        for (final reminder in customReminders)
          <String, Object?>{
            'id': reminder.id,
            'label': reminder.label,
            'subtypeValue': reminder.subtypeValue,
            // Le code brut tel qu'en base (`daily`, `weekly`, `monthly`,
            // `every_n_days`) and never a translated label: a backup will...
            // It should not depend on the language in which it was created.
            'frequency': reminder.frequency,
            'intervalDays': reminder.intervalDays,
            'babyId': reminder.babyId,
            // As it is initially defined; the import re-derives the value from `subtypeValue`, so...
            // An inconsistent value cannot take root here.
            'completionSource': reminder.completionSource,
          },
      ],
      'reminderSettings': [
        for (final setting in settings)
          <String, Object?>{
            'babyId': setting.babyId,
            'itemId': setting.itemId,
            'enabled': setting.enabled,
          },
      ],
      'reminderDismissals': [
        for (final dismissal in dismissals)
          <String, Object?>{
            'babyId': dismissal.babyId,
            'itemId': dismissal.itemId,
            'dismissedAtEpochSeconds':
                dismissal.dismissedAt.millisecondsSinceEpoch ~/ 1000,
            'dismissedAtUtc': dismissal.dismissedAt.toUtc().toIso8601String(),
          },
      ],
      'measurements': [for (final row in measurements) _mapMeasurement(row)],
      'reminderCompletions': [
        for (final completion in completions)
          <String, Object?>{
            'babyId': completion.babyId,
            'itemId': completion.itemId,
            // Journal without an ID in the document: the table is append-only.
            // The restoration process should not be able to re-associate an ID that is already in use.
            'completedAtEpochSeconds':
                completion.completedAt.millisecondsSinceEpoch ~/ 1000,
            'completedAtUtc': completion.completedAt.toUtc().toIso8601String(),
          },
      ],
    };

    return const JsonEncoder.withIndent('  ').convert(document);
  }

  @override
  Future<ExportCounts> counts() async {
    final profiles = await database.getAllBabyProfiles();
    final events = await database.getAllTrackingEvents();
    final customReminders = await database.getAllCustomReminders();
    final settings = await database.getAllReminderSettings();
    final dismissals = await database.getAllReminderDismissals();
    final measurements = await database.getAllMeasurements();
    final completions = await database.getAllReminderCompletions();
    return ExportCounts(
      babyProfiles: profiles.length,
      trackingEvents: events.length,
      customReminders: customReminders.length,
      reminderSettings: settings.length,
      reminderDismissals: dismissals.length,
      measurements: measurements.length,
      reminderCompletions: completions.length,
    );
  }

  /// Maps baby profile rows. `birth_date` is stored as epoch MILLISECONDS,
  /// so it is emitted both as the lossless integer and as an ISO8601 UTC
  /// string for humans — deliberately two fields.
  List<Map<String, Object?>> _mapProfiles(List<db_app.BabyProfile> profiles) =>
      [
        for (final profile in profiles)
          <String, Object?>{
            'id': profile.id,
            'name': profile.name,
            'birthDateEpochMs': profile.birthDate,
            'birthDateUtc': DateTime.fromMillisecondsSinceEpoch(
              profile.birthDate,
              isUtc: true,
            ).toIso8601String(),
            'isActive': profile.isActive,
          },
      ];

  /// Maps event rows. `timestamp` is stored as epoch SECONDS, so it is
  /// emitted both as the lossless integer and as an ISO8601 UTC string —
  /// deliberately two fields.
  List<Map<String, Object?>> _mapEvents(List<db_app.TrackingEvent> events) => [
        for (final row in events) _mapEvent(row),
      ];

  Map<String, Object?> _mapEvent(db_app.TrackingEvent row) {
    // The mapper is the SINGLE place where decryption happens.
    final entity = mapToEntity(row, encryption);
    final notes = _decryptedNotes(entity);

    // A row whose ciphertext exists in the database but does not decrypt
    // (lost/rotated key) must NOT be emitted as a plain null — that would
    // look like "the user wrote no note". Flag it explicitly so the silent
    // loss is visible to whoever reads the backup.
    final notesUndecryptable = row.notes != null && notes == null;

    final event = <String, Object?>{
      'id': row.id,
      'type': row.type,
      'timestampEpochSeconds': row.timestamp.millisecondsSinceEpoch ~/ 1000,
      'timestampUtc': row.timestamp.toUtc().toIso8601String(),
      'durationMinutes': row.duration,
      'subtype': row.subtype,
      'notes': notes,
      'wasteType': row.wasteType,
      'color': row.color,
      'texture': row.texture,
      'babyId': row.babyId,
      'quantity': row.quantity,
      // Unit number, as in the base model (v12). A backup that carries the...
      // A number without its unit of measurement leaves the importer to guess – and that's exactly the problem.
      // The flaw that this version fixes.
      'unit': row.unit,
    };
    if (notesUndecryptable) {
      event['notesUndecryptable'] = true;
    }
    return event;
  }

  /// Retrieve the `notes` field (which has been deciphered by the mapping process), regardless of the...
  /// subtype: The base sealed class does not directly expose it.
  String? _decryptedNotes(TrackingEvent entity) => entity.when(
        (timestamp, id, babyId) => null,
        feeding: (subtype, timestamp, unit, quantity, id, babyId, notes) =>
            notes,
        sleep: (duration, timestamp, unit, quantity, id, babyId, notes) =>
            notes,
        diaper: (timestamp, id, babyId, wasteType, pipiColor, cacaColor,
                stoolTexture, notes) =>
            notes,
        health: (subtype, timestamp, id, babyId, notes) => notes,
      );

  /// Maps a `measurements` line. `recorded_at` is stored in...
  /// seconds, therefore transmitted in their entirety without any loss and in ISO8601 UTC format — two.
  /// fields, mirroring the events.
  ///
  /// The `value` section, once deciphered, follows the same pattern as `_decryptedNotes`: a...
  /// A backup that the owner cannot access is not a backup.
  /// Instead of succeeding, the decryption fails (due to a lost or incorrect key).
  /// fail the export.
  Map<String, Object?> _mapMeasurement(db_app.Measurement row) {
    final value = encryption.decrypt(row.value);
    final valueUndecryptable = value == null;

    final notes = row.notes == null ? null : encryption.decrypt(row.notes);
    final notesUndecryptable = row.notes != null && notes == null;

    final measurement = <String, Object?>{
      'id': row.id,
      'babyId': row.babyId,
      'kind': row.kind,
      'value': value,
      'unit': row.unit,
      'recordedAtEpochSeconds': row.recordedAt.millisecondsSinceEpoch ~/ 1000,
      'recordedAtUtc': row.recordedAt.toUtc().toIso8601String(),
      'notes': notes,
    };
    if (valueUndecryptable) {
      measurement['valueUndecryptable'] = true;
    }
    if (notesUndecryptable) {
      measurement['notesUndecryptable'] = true;
    }
    return measurement;
  }
}
